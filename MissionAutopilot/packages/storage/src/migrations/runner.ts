import type { Queryable } from '../database.js'

export interface Migration {
  name: string
  up: (q: Queryable) => Promise<void>
}

/**
 * Runs all unapplied migrations. Caller is responsible for serialization
 * (initializeDatabase holds a session advisory lock on a dedicated client).
 * Each migration applies in its own transaction; a failure stops the run and
 * rolls back only the failing migration.
 */
export async function runMigrations(q: Queryable, migrations: Migration[]): Promise<void> {
  await q.query(`
    CREATE TABLE IF NOT EXISTS _migrations (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name text NOT NULL UNIQUE,
      applied_at text NOT NULL
    )
  `)
  const appliedRes = await q.query('SELECT name FROM _migrations')
  const applied = new Set(appliedRes.rows.map((r) => r.name as string))
  const pending = [...migrations]
    .sort((a, b) => a.name.localeCompare(b.name))
    .filter((m) => !applied.has(m.name))

  for (const migration of pending) {
    await q.query('BEGIN')
    try {
      await migration.up(q)
      await q.query('INSERT INTO _migrations (name, applied_at) VALUES ($1, $2)', [
        migration.name,
        new Date().toISOString(),
      ])
      await q.query('COMMIT')
    } catch (err) {
      await q.query('ROLLBACK')
      throw err
    }
  }
}
