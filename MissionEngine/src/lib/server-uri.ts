/** Lightweight parseable + http(s)-scheme check (used by the validators). */
export function hasValidServerUriScheme(uri: string): boolean {
  try {
    const u = new URL(uri);
    return u.protocol === 'http:' || u.protocol === 'https:';
  } catch {
    return false;
  }
}
