// Compiles tokens/form.json into dist/form-tokens.{light,dark}.css.
// Every custom property is prefixed --form-. camelCase keys become kebab-case.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const pkgRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const tokens = JSON.parse(readFileSync(path.join(pkgRoot, 'tokens/form.json'), 'utf8'))

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()

/** Flatten nested objects into [name, value] pairs: {type:{size:{xl:'1.5rem'}}} → type-size-xl. */
function flatten(obj, prefix = []) {
  const out = []
  for (const [key, value] of Object.entries(obj)) {
    if (value !== null && typeof value === 'object') out.push(...flatten(value, [...prefix, key]))
    else out.push([[...prefix, key].map(kebab).join('-'), String(value)])
  }
  return out
}

function buildTheme(theme) {
  const { color, breakpoint, ...shared } = tokens
  const pairs = [...flatten(shared), ...flatten({ color: color[theme] })]
  const lines = pairs.map(([name, value]) => `  --form-${name}: ${value};`)
  return `/* Generated by @mission/form-tokens build.mjs — do not edit. */\n:root {\n${lines.join('\n')}\n}\n`
}

mkdirSync(path.join(pkgRoot, 'dist'), { recursive: true })
for (const theme of ['light', 'dark']) {
  writeFileSync(path.join(pkgRoot, `dist/form-tokens.${theme}.css`), buildTheme(theme))
}
console.log('form-tokens: wrote dist/form-tokens.light.css and dist/form-tokens.dark.css')
